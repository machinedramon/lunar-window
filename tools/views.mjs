import { chromium } from 'playwright-core';
const dir = process.argv[2];
const browser = await chromium.launch({ channel: 'msedge', args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const problems = [];
page.on('console', (m) => { if (m.type() === 'error') problems.push(`console: ${m.text()}`); });
page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`));
await page.goto('http://localhost:5700/', { waitUntil: 'networkidle' });
await page.waitForTimeout(8000);
const set = (patch) => page.evaluate((p) => window.__lwStore.set(p), patch);
await set({ siteId: 'blue-ghost-1', timeMs: Date.UTC(2025, 2, 14, 8, 30) });
await page.waitForTimeout(9000);
await page.screenshot({ path: `${dir}/replay.png` });
await set({ siteId: 'malapert', timeMs: Date.UTC(2027, 0, 17) });
await page.waitForTimeout(9000);
await page.click('.hud-actions .btn:first-child');
await page.waitForTimeout(500);
await page.screenshot({ path: `${dir}/sitefile.png` });
await page.click('.hud-actions .btn:last-child');
await page.waitForTimeout(500);
await page.screenshot({ path: `${dir}/replaylist.png` });
await page.keyboard.press('Escape');
await set({ hero: 'panorama' });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${dir}/pano.png` });
console.log(problems.join('\n') || 'no errors');
await browser.close();
